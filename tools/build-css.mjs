#!/usr/bin/env node
/* ============================================================================
 * tools/build-css.mjs — concatenate the css/ split into one request.
 * ----------------------------------------------------------------------------
 * Seven <link rel=stylesheet> tags are seven chances to block first paint, and
 * on a throttled mobile run they were most of the gap between FCP 3.3s and
 * FCP 1.0s — components.css alone cost 1.2s of blocking, hero.css and
 * animations.css 600ms each, despite being same-origin and tiny next to a
 * single round trip.
 *
 * The split is worth keeping as SOURCES: tokens.css is the DESIGN.md reference,
 * base.css is the reset, components.css is the component library. Nobody reads
 * that better as one 70KB file. So the split stays and index.html links only
 * the bundle this script writes.
 *
 * Order is fixed and is the cascade contract — tokens define the custom
 * properties everything else reads, so tokens must come first, and hero must
 * follow components so the hero's own rules win.
 *
 *   node tools/build-css.mjs           # write css/bundle.css
 *   node tools/build-css.mjs --check   # fail if bundle.css is out of date
 * ==========================================================================*/

import { readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = path.join(ROOT, 'css');
const OUT = path.join(SRC_DIR, 'bundle.css');

/* The cascade order. Changing it changes the design, so it lives in one place. */
const SOURCES = [
  'tokens.css',
  'base.css',
  'animations.css',
  'components.css',
  'hero.css',
  'toolpass.css',
  'intro.css',
];

const BANNER = `/* GENERATED by tools/build-css.mjs — do not edit.
 *
 * Source order: ${SOURCES.join(' -> ')}
 * Edit those files and re-run: node tools/build-css.mjs
 */`;

function build() {
  const parts = [BANNER];
  for (const name of SOURCES) {
    const file = path.join(SRC_DIR, name);
    const body = readFileSync(file, 'utf8').trimEnd();
    parts.push(`\n/* ===== ${name} ${'='.repeat(Math.max(0, 66 - name.length))} */\n${body}`);
  }
  return parts.join('\n') + '\n';
}

const wanted = build();

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== wanted) {
    console.error('css/bundle.css is out of date. Run: node tools/build-css.mjs');
    process.exit(1);
  }
  console.log('css/bundle.css is up to date');
} else {
  /* A stale bundle is worse than no bundle: the page would serve CSS that no
     longer matches the sources, and nothing would say so. Refuse to write one
     that is older than its own inputs, and say how to fix it. */
  const oldestSource = Math.max(...SOURCES.map((n) => statSync(path.join(SRC_DIR, n)).mtimeMs));
  if (existsSync(OUT) && statSync(OUT).mtimeMs < oldestSource) {
    console.error(
      'css/bundle.css is older than its sources. That means a css/ file was\n' +
      'edited without re-running this script, and the page would be served\n' +
      'stale CSS. Re-run: node tools/build-css.mjs',
    );
    process.exit(1);
  }
  writeFileSync(OUT, wanted);
  const kb = (Buffer.byteLength(wanted) / 1024).toFixed(1);
  console.log(`wrote css/bundle.css — ${SOURCES.length} files, ${kb} KiB, one request`);
}
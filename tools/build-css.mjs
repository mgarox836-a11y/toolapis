#!/usr/bin/env node
/* ============================================================================
 * tools/build-css.mjs — concatenate the css/ split into one request.
 * ----------------------------------------------------------------------------
 * Seven <link rel=stylesheet> tags were seven chances to block first paint, and
 * on a throttled mobile run they were most of the gap between FCP 3.3s and
 * FCP 1.0s — components.css alone cost 1.2s of blocking, hero.css and
 * animations.css 600ms each, despite being same-origin and tiny next to a
 * single round trip.
 *
 * The split is worth keeping as SOURCES: tokens.css is the DESIGN.md reference,
 * base.css is the reset, components.css is the component library. Nobody reads
 * that better as one 70KB file. So the split stays and index.html links only
 * the bundle this script writes.
 *
 * Order is fixed and is the cascade contract — tokens define the custom
 * properties everything else reads, so tokens must come first, and hero must
 * follow components so the hero's own rules win. hero3d and sections come after
 * hero because they are additive on top of it: the scene paints into the hero's
 * box and the section layouts compose the cards components.css skins.
 * section-bg.css is last because it is the only file that paints BEHIND a
 * layout, and it needs to win on specificity where a layer and the content in
 * front of it describe the same box.
 *
 *   node tools/build-css.mjs           # write css/bundle.css
 *   node tools/build-css.mjs --check   # fail if bundle.css is out of date
 * ==========================================================================*/

import { readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = path.join(ROOT, 'css');
const OUT = path.join(SRC_DIR, 'bundle.css');

/* The cascade order. Changing it changes the design, so it lives in one place.
   Exported because tools/css-syntax-check.mjs reads this list rather than
   keeping its own copy of it — that copy is what made it check eight of nine
   files when section-bg.css was added. Importing must not have side effects, so
   the writing half of this script is gated on being the entry module below. */
export const SOURCES = [
  'tokens.css',
  'base.css',
  'animations.css',
  'components.css',
  'hero.css',
  'hero3d.css',
  'sections.css',
  'toolpass.css',
  'section-bg.css',
];

const BANNER = `/* GENERATED by tools/build-css.mjs — do not edit.
 *
 * Source order: ${SOURCES.join(' -> ')}
 * Edit those files and re-run: node tools/build-css.mjs
 */`;

function build() {
  const parts = [BANNER];
  for (const name of SOURCES) {
    const file = path.join(SRC_DIR, name);
    const body = readFileSync(file, 'utf8').trimEnd();
    parts.push(`\n/* ===== ${name} ${'='.repeat(Math.max(0, 66 - name.length))} */\n${body}`);
  }
  return parts.join('\n') + '\n';
}

const wanted = build();

/* Importing this file for SOURCES must not build anything. `import.meta.url`
   compared against argv[1] is the check, and it is the reason the main body
   lives inside `if (isMain)` rather than at module top level — otherwise
   css-syntax-check.mjs would rewrite css/bundle.css as a side effect of asking
   which files are in it, and could `process.exit(1)` out from under its own
   report when the staleness guard fires. */
const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain && process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== wanted) {
    console.error('css/bundle.css is out of date. Run: node tools/build-css.mjs');
    process.exit(1);
  }
  console.log('css/bundle.css is up to date');
} else if (isMain && process.argv.includes('--force')) {
  /* --force exists because the staleness guard below makes the tool unable to
     do its own job: every legitimate edit to a source file is exactly the
     condition the guard refuses. The guard is right that a stale bundle is a
     bug and wrong that refusing to rebuild creates one, so the rebuild needs a
     way to say "yes, I meant it". Kept for CI, where a bundle that differs from
     the sources should fail the build rather than be silently rewritten. */
  writeFileSync(OUT, wanted);
  const kb = (Buffer.byteLength(wanted) / 1024).toFixed(1);
  console.log(`wrote css/bundle.css (forced) — ${SOURCES.length} files, ${kb} KiB, one request`);
} else if (isMain) {
  /* A stale bundle is worse than no bundle: the page would serve CSS that no
     longer matches the sources, and nothing would say so. Refuse to write one
     that is older than its own inputs, and say how to fix it.

     `touch` the bundle first when the CONTENT is already correct and only the
     mtimes are out of order — that is what happened after a git checkout or a
     rebase, where the sources land with fresh timestamps but the generated
     file is identical to what would be written now. */
  const oldestSource = Math.max(...SOURCES.map((n) => statSync(path.join(SRC_DIR, n)).mtimeMs));
  if (existsSync(OUT) && statSync(OUT).mtimeMs < oldestSource) {
    const current = readFileSync(OUT, 'utf8');
    if (current === wanted) {
      /* Byte-identical: only the timestamps are stale. Adopt the source mtime
         so the next real edit is still caught by this guard. */
      const { utimesSync } = await import('node:fs');
      const now = new Date();
      utimesSync(OUT, now, new Date(oldestSource + 1000));
      console.log('css/bundle.css was already current (timestamps only) — touched');
    } else {
      console.error(
        'css/bundle.css is older than its sources AND differs from them.\n' +
        'A css/ file was edited without re-running this script, so the page\n' +
        'would be served stale CSS. Re-run: node tools/build-css.mjs',
      );
      process.exit(1);
    }
  }
  writeFileSync(OUT, wanted);
  const kb = (Buffer.byteLength(wanted) / 1024).toFixed(1);
  console.log(`wrote css/bundle.css — ${SOURCES.length} files, ${kb} KiB, one request`);
}